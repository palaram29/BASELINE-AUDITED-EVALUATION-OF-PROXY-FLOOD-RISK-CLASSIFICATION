"""
Record the exact environment that produced the reported results.

The review flagged reproducibility because library and runtime versions
were not documented anywhere: requirements.txt lists package names with
no version constraints, so reinstalling from it does not reproduce the
environment the numbers came from.

This script writes ML/reports/environment.json with the Python version,
platform, CPU count, and the resolved version of every library that
affects a result (the three learners, scikit-learn, numpy, pandas), plus
the fixed seeds and split boundaries used throughout the pipeline. Run it
alongside ML/train_models.py and cite the output in the paper's
reproducibility table.

Usage:
    python ML/environment_report.py
"""

import os
import sys
import json
import platform
from datetime import datetime, timezone

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from ML.utils import logger, ensure_dirs, REPORTS_DIR

# Libraries whose version can change a reported number. Anything that only
# affects serving or presentation (fastapi, matplotlib, and so on) is
# deliberately left out, since it cannot move a metric.
RESULT_AFFECTING_PACKAGES = [
    "scikit-learn",
    "xgboost",
    "lightgbm",
    "numpy",
    "pandas",
    "scipy",
]

# Fixed values used across the pipeline. Collected here so the paper's
# reproducibility table has one source rather than several scattered
# constants.
PIPELINE_CONSTANTS = {
    "global_seed": 42,
    "n_estimators": 100,
    "learning_rate": 0.1,
    "train_period": "2010-01-03 to 2019-12-30",
    "validation_period": "2018-01-01 to 2019-12-30 (held out from within training)",
    "inner_train_period": "2010-01-03 to 2017-12-31",
    "test_period": "2020-01-01 to 2023-06-16",
    "train_rows": 109470,
    "test_rows": 37890,
    "walkforward_folds": [
        "train<=2016 -> test 2017",
        "train<=2017 -> test 2018",
        "train<=2018 -> test 2019",
        "train<=2019 -> test 2020",
        "train<=2020 -> test 2021",
        "train<=2021 -> test 2022",
    ],
    "bootstrap_resamples": 1000,
    "bootstrap_block_unit": "calendar month",
    "permutation_repeats": 5,
    "class_weighting": {
        "RandomForest": "class_weight='balanced'",
        "LightGBM": "class_weight='balanced'",
        "XGBoost": "balanced sample_weight computed from y_train at fit time",
    },
}


def _package_versions():
    """Resolved version of each result-affecting package, or a marker if
    the package is not importable in this environment."""

    try:
        from importlib.metadata import version, PackageNotFoundError
    except ImportError:  # pragma: no cover - Python < 3.8 only
        return {name: "unknown" for name in RESULT_AFFECTING_PACKAGES}

    versions = {}
    for name in RESULT_AFFECTING_PACKAGES:
        try:
            versions[name] = version(name)
        except PackageNotFoundError:
            versions[name] = "not installed"
    return versions


def build_report():
    ensure_dirs()

    report = {
        "captured_at": datetime.now(timezone.utc).isoformat(),
        "runtime": {
            "python_version": sys.version.split()[0],
            "python_implementation": platform.python_implementation(),
            "platform": platform.platform(),
            "processor": platform.processor() or "unknown",
            "cpu_count": os.cpu_count(),
        },
        "packages": _package_versions(),
        "pipeline_constants": PIPELINE_CONSTANTS,
        "note": (
            "requirements.txt lists package names without version "
            "constraints, so it installs a working environment but does "
            "not reproduce this one. requirements.lock.txt, generated by "
            "pip freeze, is the exact record; this file captures the "
            "subset of it that can change a reported metric."
        ),
    }

    out_path = os.path.join(REPORTS_DIR, "environment.json")
    with open(out_path, "w") as f:
        json.dump(report, f, indent=2)
    logger.info(f"Saved environment report -> {out_path}")

    print("\n===== ENVIRONMENT =====\n")
    print(f"Python        {report['runtime']['python_version']}")
    print(f"Platform      {report['runtime']['platform']}")
    print(f"CPU count     {report['runtime']['cpu_count']}")
    print()
    for name, ver in report["packages"].items():
        print(f"{name:16s} {ver}")
    print()
    print(f"Written to {out_path}")
    print("Cite these values in the paper's reproducibility table.")

    return report


if __name__ == "__main__":
    build_report()
